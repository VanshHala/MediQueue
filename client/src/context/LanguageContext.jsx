const LanguageContext = createContext(null);

export const SUPPORTED_LANGUAGES = [
  { code: 'en', label: 'English', short: 'EN' },
  { code: 'hi', label: 'हिन्दी', short: 'HI' },
  { code: 'gu', label: 'ગુજરાતી', short: 'GU' },
];

export const LanguageProvider = ({ children }) => {
  const [lang, setLang] = useState(() => {
    try {
      const saved = localStorage.getItem('mediqueue_lang');
      if (saved && (saved === 'en' || saved === 'hi' || saved === 'gu')) {
        return saved;
      }
    } catch {
      // ignore
    }
    return 'en';
  });

  const changeLanguage = (newLang) => {
    if (newLang === 'en' || newLang === 'hi' || newLang === 'gu') {
      setLang(newLang);
      try {
        localStorage.setItem('mediqueue_lang', newLang);
      } catch {
        // ignore
      }
    }
  };

  const t = (key, fallback = '') => {
    const langDict = translations[lang] || translations.en;
    if (langDict[key] !== undefined) {
      return langDict[key];
    }
    if (translations.en[key] !== undefined) {
      return translations.en[key];
    }
    return fallback || key;
  };

  return (
    <LanguageContext.Provider
      value={{
        lang,
        changeLanguage,
        t,
        languages: SUPPORTED_LANGUAGES,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};

export default LanguageContext;
